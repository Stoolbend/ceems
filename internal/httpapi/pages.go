// maxPageBody caps a page upload body.
const maxPageBody = 256 << 10

// pageDoc is the page document of GET and PUT /api/v1/pages/{mpp} and of an upload response.
type pageDoc struct {
	MPP         string       `json:"mpp"`
	Description string       `json:"description"`
	Transmit    bool         `json:"transmit"`
	UpdatedAt   string       `json:"updatedAt"`
	UpdatedBy   string       `json:"updatedBy"`
	ETag        string       `json:"etag"`
	Subpages    []subpageDoc `json:"subpages"`
	Binding     *bindingRef  `json:"binding"`      // null when no binding generates the page; ignored on PUT
	Fastext     *fastextRef  `json:"fastextGroup"` // null when the page is in no group; ignored on PUT
	CanWrite    bool         `json:"canWrite"`     // whether the caller may write this page; ignored on PUT
}

// fastextRef names the fastext group a page belongs to.
type fastextRef struct {
	ID    int64  `json:"id"`
	Name  string `json:"name"`
	Paged bool   `json:"paged"`
}

// bindingRef names the binding that generates a page.
type bindingRef struct {
	ID   int64  `json:"id"`
	Name string `json:"name"`
}

// subpageDoc is one subpage. Rows has 25 entries (index = row); null means no OL line.
// Null cycle fields or links mean the CT or FL line is absent or unparseable.
type subpageDoc struct {
	CycleSeconds *int      `json:"cycleSeconds"`
	CycleMode    *string   `json:"cycleMode"`
	Links        []string  `json:"links"`
	Rows         []*string `json:"rows"`
}

// pageJSON builds the document from a stored page. Stored bytes were validated on
// write, so a parse failure cannot happen; it would yield no subpages.
func pageJSON(p *store.Page, canWrite bool) pageDoc {
	d := pageDoc{
		MPP: fmt.Sprintf("%03X", p.MPP), Description: p.Description, Transmit: p.Transmit,
		UpdatedAt: p.UpdatedAt, UpdatedBy: p.UpdatedBy, ETag: p.ETag(), Subpages: []subpageDoc{},
		CanWrite: canWrite,
	}
	if p.BindingID != nil {
		d.Binding = &bindingRef{ID: *p.BindingID, Name: p.BindingName}
	}
	if p.FastextGroupID != nil {
		d.Fastext = &fastextRef{ID: *p.FastextGroupID, Name: p.FastextGroupName, Paged: p.FastextPaged}
	}
	t, err := tti.Parse(p.TTI)
	if err != nil {
		return d
	}
	for i := 0; i < t.Subpages(); i++ {
		s := subpageDoc{Rows: make([]*string, 25)}
		if body, ok := t.Field(i, "CT"); ok {
			if sec, mode, ok := tti.ParseCT(body); ok {
				m := string(mode)
				s.CycleSeconds, s.CycleMode = &sec, &m
			}
		}
		if body, ok := t.Field(i, "FL"); ok {
			if l, ok := tti.ParseFL(body); ok {
				s.Links = l[:]
			}
		}
		for r := range s.Rows {
			if c, ok := t.Row(i, r); ok {
				s.Rows[r] = &c
			}
		}
		d.Subpages = append(d.Subpages, s)
	}
	return d
}

// readBody reads a page request body of at most maxPageBody bytes, writing the error response itself.
func readBody(w http.ResponseWriter, r *http.Request) ([]byte, bool) {
	body, err := io.ReadAll(http.MaxBytesReader(w, r.Body, maxPageBody))
	var tooBig *http.MaxBytesError
	if errors.As(err, &tooBig) {
		writeError(w, http.StatusRequestEntityTooLarge, "too_large", "page file is larger than 256 KiB")
		return nil, false
	}
	if err != nil {
		writeError(w, http.StatusBadRequest, "bad_request", "could not read the request body")
		return nil, false
	}
	return body, true
}

// audit builds the request-derived part of an audit row; the store fills the rest.
func audit(r *http.Request, action string) store.Audit {
	return store.Audit{Actor: principalFrom(r).Actor, Action: action, Remote: clientIP(r)}
}

// ifMatch is the If-Match header with surrounding double quotes stripped.
func ifMatch(r *http.Request) string { return strings.Trim(r.Header.Get("If-Match"), `"`) }

// pageError maps a store error from a page write to its response.
func (a *api) pageError(w http.ResponseWriter, err error) {
	switch {
	case errors.Is(err, store.ErrNotFound):
		writeError(w, http.StatusNotFound, "not_found", "no such page")
	case errors.Is(err, store.ErrGenerated):
		writeError(w, http.StatusConflict, "generated_page", "page is generated by a binding and cannot be edited")
	case errors.Is(err, store.ErrStale):
		writeError(w, http.StatusPreconditionFailed, "precondition_failed", "page changed since it was loaded; reload and try again")
	case errors.Is(err, store.ErrExists):
		writeError(w, http.StatusConflict, "exists", "page already exists")
	default:
		a.internalError(w, err)
	}
}

func (a *api) downloadPage(w http.ResponseWriter, r *http.Request, mpp int) {
	p, err := a.db.Page(mpp)
	if err != nil {
		a.pageError(w, err)
		return
	}
	w.Header().Set("Content-Type", "application/octet-stream")
	w.Header().Set("Content-Disposition", fmt.Sprintf(`attachment; filename="P%03X.tti"`, mpp))
	w.Write(p.TTI)
}

func (a *api) uploadPage(w http.ResponseWriter, r *http.Request, mpp int) {
	body, ok := readBody(w, r)
	if !ok {
		return
	}
	p, err := tti.Parse(body)
	if err != nil {
		writeError(w, http.StatusBadRequest, "invalid_tti", err.Error())
		return
	}
	if p.MPP() != mpp {
		writeError(w, http.StatusBadRequest, "mpp_mismatch", fmt.Sprintf("file is page %03X but the target is page %03X", p.MPP(), mpp))
		return
	}
	if _, err := a.db.SavePage(mpp, p, ifMatch(r), audit(r, "page.upload")); err != nil {
		a.pageError(w, err)
		return
	}
	saved, err := a.db.Page(mpp)
	if err != nil {
		a.pageError(w, err)
		return
	}
	writeJSON(w, http.StatusOK, pageJSON(saved, principalFrom(r).Can(mpp, true)))
}

// updatePage applies a page document to the stored page's lines, so only what the
// client changed is rewritten, then saves it under If-Match.
// shortcut: a non-UTF-8 DE body would be mangled by JSON and rewritten on save; no fixture has one.
func (a *api) updatePage(w http.ResponseWriter, r *http.Request, mpp int) {
	body, ok := readBody(w, r)
	if !ok {
		return
	}
	var d pageDoc
	if err := json.Unmarshal(body, &d); err != nil {
		writeError(w, http.StatusBadRequest, "bad_request", "body is not a page document")
		return
	}
	stored, err := a.db.Page(mpp)
	if err != nil {
		a.pageError(w, err)
		return
	}
	p, err := tti.Parse(stored.TTI)
	if err != nil {
		a.internalError(w, err)
		return
	}
	if err := applyDoc(p, d); err != nil {
		writeError(w, http.StatusBadRequest, "invalid_page", err.Error())
		return
	}
	if _, err := a.db.SavePage(mpp, p, ifMatch(r), audit(r, "page.update")); err != nil {
		a.pageError(w, err)
		return
	}
	saved, err := a.db.Page(mpp)
	if err != nil {
		a.pageError(w, err)
		return
	}
	writeJSON(w, http.StatusOK, pageJSON(saved, principalFrom(r).Can(mpp, true)))
}

// applyDoc validates d and applies it to p in the order of the T-009 design.
func applyDoc(p *tti.Page, d pageDoc) error {
	if n := len(d.Subpages); n < 1 || n > 99 {
		return fmt.Errorf("a page needs 1-99 subpages, got %d", n)
	}
	for p.Subpages() < len(d.Subpages) {
		p.AddSubpage()
	}
	for p.Subpages() > len(d.Subpages) {
		if err := p.RemoveSubpage(p.Subpages() - 1); err != nil {
			return err
		}
	}
	for i, s := range d.Subpages {
		if err := applyCycle(p, i, s); err != nil {
			return fmt.Errorf("subpage %d: %w", i+1, err)
		}
		if err := applyLinks(p, i, s.Links); err != nil {
			return fmt.Errorf("subpage %d: %w", i+1, err)
		}
		for r := 1; r <= 24 && r < len(s.Rows); r++ {
			if s.Rows[r] == nil {
				continue
			}
			if err := p.SetRow(i, r, *s.Rows[r]); err != nil {
				return fmt.Errorf("subpage %d row %d: %w", i+1, r, err)
			}
		}
	}
	if strings.ContainsAny(d.Description, "\r\n") || len(d.Description) > 255 {
		return fmt.Errorf("description must be one line of at most 255 bytes")
	}
	if d.Description != p.Description() {
		p.SetField(-1, "DE", d.Description)
	}
	p.SetTransmit(d.Transmit)
	return nil
}

func applyCycle(p *tti.Page, i int, s subpageDoc) error {
	if s.CycleSeconds == nil {
		return nil
	}
	sec, mode := *s.CycleSeconds, ""
	if s.CycleMode != nil {
		mode = *s.CycleMode
	}
	if sec < 1 || sec > 999 || (mode != "T" && mode != "C") {
		return fmt.Errorf("cycle time must be 1-999 seconds with mode T or C")
	}
	body, _ := p.Field(i, "CT")
	if s0, m0, ok := tti.ParseCT(body); !ok || s0 != sec || string(m0) != mode {
		p.SetField(i, "CT", fmt.Sprintf("%d,%s", sec, mode))
	}
	return nil
}

func applyLinks(p *tti.Page, i int, links []string) error {
	if links == nil {
		return nil
	}
	if len(links) != 6 {
		return fmt.Errorf("want six links, got %d", len(links))
	}
	var want [6]string
	for k, l := range links {
		if _, err := strconv.ParseUint(l, 16, 12); err != nil || len(l) != 3 {
			return fmt.Errorf("link %d must be three hex digits", k+1)
		}
		want[k] = strings.ToLower(l)
	}
	body, _ := p.Field(i, "FL")
	if have, ok := tti.ParseFL(body); !ok || have != want {
		p.SetField(i, "FL", strings.Join(want[:], ","))
	}
	return nil
}

// createPage makes a blank page at mpp; 409 when it exists.
func (a *api) createPage(w http.ResponseWriter, r *http.Request, mpp int) {
	if err := a.db.CreatePage(tti.NewPage(mpp), audit(r, "page.create")); err != nil {
		if errors.Is(err, store.ErrExists) {
			writeError(w, http.StatusConflict, "exists", fmt.Sprintf("page %03X already exists", mpp))
			return
		}
		a.pageError(w, err)
		return
	}
	saved, err := a.db.Page(mpp)
	if err != nil {
		a.pageError(w, err)
		return
	}
	writeJSON(w, http.StatusCreated, pageJSON(saved, principalFrom(r).Can(mpp, true)))
}

// deletePage removes a page; the page's etag in If-Match is the confirmation, and an
// empty one must never reach the store, where it would mean "no precondition".
func (a *api) deletePage(w http.ResponseWriter, r *http.Request, mpp int) {
	etag := ifMatch(r)
	if etag == "" {
		writeError(w, http.StatusPreconditionRequired, "confirmation_required", "send If-Match with the page's etag to confirm deletion")
		return
	}
	if err := a.db.DeletePage(mpp, etag, audit(r, "page.delete")); err != nil {
		a.pageError(w, err)
		return
	}
	w.WriteHeader(http.StatusNoContent)
}
