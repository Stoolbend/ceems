// runDoc is one run as clients see it.
type runDoc struct {
	ID         int64  `json:"id"`
	Actor      string `json:"actor"`
	StartedAt  string `json:"startedAt"`
	FinishedAt string `json:"finishedAt"`
	Outcome    string `json:"outcome"`
	Error      string `json:"error"`
}

func runJSON(r store.Run) runDoc {
	return runDoc{ID: r.ID, Actor: r.Actor, StartedAt: r.StartedAt, FinishedAt: r.FinishedAt, Outcome: r.Outcome, Error: r.Error}
}

// bindingItem is one entry of the binding list. It never carries source or static:
// the sheet id appears only in the single binding document (ADR 0005).
type bindingItem struct {
	ID           int64   `json:"id"`
	Name         string  `json:"name"`
	TemplateID   int64   `json:"templateId"`
	TemplateName string  `json:"templateName"`
	MPP          string  `json:"mpp"`
	LastRun      *runDoc `json:"lastRun"`
}

// bindingDoc is the document of GET /api/v1/bindings/{id} and of a create or update.
type bindingDoc struct {
	ID           int64           `json:"id"`
	Name         string          `json:"name"`
	TemplateID   int64           `json:"templateId"`
	TemplateName string          `json:"templateName"`
	MPP          string          `json:"mpp"`
	Source       json.RawMessage `json:"source"`
	Static       json.RawMessage `json:"static"`
}

// bindingBody is the POST and PUT body; nil fields were absent.
type bindingBody struct {
	Name       *string         `json:"name"`
	TemplateID *int64          `json:"templateId"`
	MPP        *string         `json:"mpp"`
	Source     json.RawMessage `json:"source"`
	Static     json.RawMessage `json:"static"`
}

func isObject(raw json.RawMessage) bool {
	t := bytes.TrimSpace(raw)
	return len(t) > 0 && t[0] == '{'
}

// bindingID returns the {id} path value, writing a 404 itself when it is not a positive integer.
func bindingID(w http.ResponseWriter, r *http.Request) (int64, bool) {
	id, err := strconv.ParseInt(r.PathValue("id"), 10, 64)
	if err != nil || id < 1 {
		writeError(w, http.StatusNotFound, "not_found", "no such binding")
		return 0, false
	}
	return id, true
}

// bindingError maps a store error from a binding call to its response.
func (a *api) bindingError(w http.ResponseWriter, err error, mpp int) {
	switch {
	case errors.Is(err, store.ErrNotFound):
		writeError(w, http.StatusNotFound, "not_found", "no such binding")
	case errors.Is(err, store.ErrBound):
		writeError(w, http.StatusConflict, "page_bound", fmt.Sprintf("page %03X is already generated by another binding", mpp))
	case errors.Is(err, store.ErrNameTaken):
		writeError(w, http.StatusConflict, "exists", "a binding with that name already exists")
	case errors.Is(err, store.ErrExists):
		writeError(w, http.StatusConflict, "exists", fmt.Sprintf("page %03X already exists; the binding was not moved", mpp))
	default:
		a.internalError(w, err)
	}
}

// readBinding decodes and validates a binding body before any store write, in the
// order of the T-015 design record; stored is nil on POST. It writes the error
// response itself. No message carries the sheet value.
func (a *api) readBinding(w http.ResponseWriter, r *http.Request, stored *store.Binding) (*store.Binding, bool) {
	body, ok := readBody(w, r)
	if !ok {
		return nil, false
	}
	var b bindingBody
	if err := json.Unmarshal(body, &b); err != nil || b.Name == nil || b.TemplateID == nil || b.MPP == nil || b.Source == nil || b.Static == nil {
		writeError(w, http.StatusBadRequest, "bad_request", "body must be {name, templateId, mpp, source, static}")
		return nil, false
	}
	name := strings.TrimSpace(*b.Name)
	if name == "" || len(name) > 100 || strings.ContainsAny(name, "\r\n") {
		writeError(w, http.StatusBadRequest, "bad_request", "name must be one line of 1-100 bytes")
		return nil, false
	}

	t, err := a.db.Template(*b.TemplateID)
	if errors.Is(err, store.ErrNotFound) {
		writeError(w, http.StatusBadRequest, "bad_request", "no such template")
		return nil, false
	}
	if err != nil {
		a.internalError(w, err)
		return nil, false
	}

	n, err := strconv.ParseUint(*b.MPP, 16, 16)
	if len(*b.MPP) != 3 || err != nil || n < 0x100 || n > 0x8FF {
		writeError(w, http.StatusBadRequest, "bad_request", "mpp must be three hex digits in magazines 1-8")
		return nil, false
	}
	mpp := int(n)
	if stored == nil {
		bs, err := a.db.Bindings()
		if err != nil {
			a.internalError(w, err)
			return nil, false
		}
		for _, o := range bs {
			if o.MPP == mpp {
				writeError(w, http.StatusConflict, "exists", fmt.Sprintf("page %03X already has a binding", mpp))
				return nil, false
			}
		}
	}

	if !isObject(b.Source) {
		writeError(w, http.StatusBadRequest, "invalid_source", "source must be an object")
		return nil, false
	}
	cfg, err := jobs.ParseSourceConfig(string(b.Source))
	if err != nil {
		writeError(w, http.StatusBadRequest, "invalid_source", err.Error())
		return nil, false
	}
	if cfg.Format == nil {
		cfg.Format = map[string]string{}
	}

	var static map[string]string
	if !isObject(b.Static) || json.Unmarshal(b.Static, &static) != nil {
		writeError(w, http.StatusBadRequest, "invalid_static", "static must be an object of string values")
		return nil, false
	}
	p, _, err := parseTemplate(t)
	if err != nil {
		a.internalError(w, err)
		return nil, false
	}
	data := jobs.DataKeys(cfg)
	want := map[string]bool{}
	for _, s := range p.Slots() {
		if !data[s.Name] {
			want[s.Name] = true
		}
	}
	keys := make([]string, 0, len(static))
	for k := range static {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		if !want[k] {
			writeError(w, http.StatusBadRequest, "invalid_static", fmt.Sprintf("slot %s is not a fixed slot of template %s", k, t.Name))
			return nil, false
		}
		for _, c := range static[k] {
			if c > 0x7F {
				writeError(w, http.StatusBadRequest, "invalid_static", fmt.Sprintf("slot %s: character outside 0-127", k))
				return nil, false
			}
		}
	}
	if m := missingSlots(p, data, static); len(m) > 0 { // slot order, so the first missing slot on the page is named
		writeError(w, http.StatusBadRequest, "invalid_static", fmt.Sprintf("slot %s needs a value", m[0]))
		return nil, false
	}

	src, err := json.Marshal(cfg)
	if err != nil {
		a.internalError(w, err)
		return nil, false
	}
	st, err := json.Marshal(static)
	if err != nil {
		a.internalError(w, err)
		return nil, false
	}
	return &store.Binding{Name: name, TemplateID: t.ID, MPP: mpp, Source: string(src), Static: string(st)}, true
}

// missingSlots lists, in slot order and once each, the slots of p that neither the
// source (data) nor the static values fill. The one rule shared by a binding save
// and a template update.
func missingSlots(p *tmpl.Template, data map[string]bool, static map[string]string) []string {
	var out []string
	seen := map[string]bool{}
	for _, s := range p.Slots() {
		if _, ok := static[s.Name]; !data[s.Name] && !ok && !seen[s.Name] {
			seen[s.Name] = true
			out = append(out, s.Name)
		}
	}
	return out
}

func (a *api) listBindings(w http.ResponseWriter, r *http.Request) {
	bs, err := a.db.Bindings()
	if err != nil {
		a.internalError(w, err)
		return
	}
	ts, err := a.db.Templates()
	if err != nil {
		a.internalError(w, err)
		return
	}
	last, err := a.db.LastRuns()
	if err != nil {
		a.internalError(w, err)
		return
	}
	names := map[int64]string{}
	for _, t := range ts {
		names[t.ID] = t.Name
	}
	out := []bindingItem{}
	for _, b := range bs {
		it := bindingItem{ID: b.ID, Name: b.Name, TemplateID: b.TemplateID, TemplateName: names[b.TemplateID], MPP: fmt.Sprintf("%03X", b.MPP)}
		if run, ok := last[b.ID]; ok {
			d := runJSON(run)
			it.LastRun = &d
		}
		out = append(out, it)
	}
	writeJSON(w, http.StatusOK, map[string]any{
		"sheetsConfigured": a.runner != nil && a.runner.SheetsConfigured(),
		"bindings":         out,
	})
}

// writeBinding answers status with the stored binding id's document.
func (a *api) writeBinding(w http.ResponseWriter, status int, id int64) {
	b, err := a.db.Binding(id)
	if err != nil {
		a.bindingError(w, err, 0)
		return
	}
	t, err := a.db.Template(b.TemplateID)
	if err != nil {
		a.internalError(w, err)
		return
	}
	writeJSON(w, status, bindingDoc{ID: b.ID, Name: b.Name, TemplateID: b.TemplateID, TemplateName: t.Name,
		MPP: fmt.Sprintf("%03X", b.MPP), Source: json.RawMessage(b.Source), Static: json.RawMessage(b.Static)})
}

func (a *api) getBinding(w http.ResponseWriter, r *http.Request) {
	if id, ok := bindingID(w, r); ok {
		a.writeBinding(w, http.StatusOK, id)
	}
}

func (a *api) createBinding(w http.ResponseWriter, r *http.Request) {
	b, ok := a.readBinding(w, r, nil)
	if !ok {
		return
	}
	id, err := a.db.CreateBinding(b, audit(r, ""))
	if err != nil {
		a.bindingError(w, err, b.MPP)
		return
	}
	a.writeBinding(w, http.StatusCreated, id)
}

func (a *api) updateBinding(w http.ResponseWriter, r *http.Request) {
	id, ok := bindingID(w, r)
	if !ok {
		return
	}
	stored, err := a.db.Binding(id)
	if err != nil {
		a.bindingError(w, err, 0)
		return
	}
	b, ok := a.readBinding(w, r, stored)
	if !ok {
		return
	}
	b.ID = id
	if err := a.db.UpdateBinding(b, audit(r, "")); err != nil {
		a.bindingError(w, err, b.MPP)
		return
	}
	a.writeBinding(w, http.StatusOK, id)
}

func (a *api) deleteBinding(w http.ResponseWriter, r *http.Request) {
	id, ok := bindingID(w, r)
	if !ok {
		return
	}
	if err := a.db.DeleteBinding(id, audit(r, "")); err != nil {
		a.bindingError(w, err, 0)
		return
	}
	w.WriteHeader(http.StatusNoContent)
}

// runBinding runs one binding synchronously and answers with its run row; a failed
// run is still 200. The run outlives a dropped connection so it is always recorded.
func (a *api) runBinding(w http.ResponseWriter, r *http.Request) {
	id, ok := bindingID(w, r)
	if !ok {
		return
	}
	if a.runner == nil {
		writeError(w, http.StatusServiceUnavailable, "scheduler_off", "the scheduler is not running")
		return
	}
	run, err := a.runner.RunNow(context.WithoutCancel(r.Context()), id, principalFrom(r).Actor)
	switch {
	case errors.Is(err, jobs.ErrBusy):
		writeError(w, http.StatusConflict, "run_in_progress", "a run is in progress; try again shortly")
	case err != nil:
		a.bindingError(w, err, 0)
	default:
		writeJSON(w, http.StatusOK, runJSON(run))
	}
}

func (a *api) listRuns(w http.ResponseWriter, r *http.Request) {
	id, ok := bindingID(w, r)
	if !ok {
		return
	}
	if _, err := a.db.Binding(id); err != nil {
		a.bindingError(w, err, 0)
		return
	}
	rs, err := a.db.Runs(id)
	if err != nil {
		a.internalError(w, err)
		return
	}
	out := []runDoc{}
	for _, run := range rs {
		out = append(out, runJSON(run))
	}
	writeJSON(w, http.StatusOK, map[string]any{"runs": out})
}
